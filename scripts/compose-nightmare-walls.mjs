/**
 * Tile Grok Imagine cave wall art into 256×256 PNGs for in-game fills.
 * Run: node scripts/compose-nightmare-walls.mjs
 */
import { createCanvas, loadImage } from 'canvas';
import { mkdirSync, readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const GEN_DIR = join(ROOT, 'assets/textures/nightmare/generated');
const OUT_DIR = join(ROOT, 'assets/textures/nightmare/walls');
const SPRITE_DIR = join(ROOT, 'assets/textures/nightmare/sprites');
const EMBED_OUT = join(ROOT, 'js/nightmare-wall-tiles.js');

const TILE = 256;

const WALLS = [
  { slug: 'stone', gen: 'wall-stone.jpg', sprite: 'wall-stone.png' },
  { slug: 'door', gen: 'wall-door.jpg', sprite: 'wall-door.png' },
];

function centerCropSquare(img) {
  const side = Math.min(img.width, img.height);
  const sx = Math.floor((img.width - side) * 0.5);
  const sy = Math.floor((img.height - side) * 0.5);
  return { sx, sy, side };
}

/** Darken and desaturate for underground cave walls; keep organic rock tones. */
function tunePixels(d, slug) {
  for (let i = 0; i < d.length; i += 4) {
    const r = d[i];
    const g = d[i + 1];
    const b = d[i + 2];
    const lum = (r + g + b) / 3;

    if (slug === 'door') {
      const warm = 0.88 + (lum / 255) * 0.08;
      d[i] = Math.min(255, r * warm * 1.02);
      d[i + 1] = Math.min(255, g * warm * 0.92);
      d[i + 2] = Math.min(255, b * warm * 0.82);
    } else {
      const shade = 0.72 + (lum / 255) * 0.1;
      d[i] = Math.min(255, r * shade);
      d[i + 1] = Math.min(255, g * shade * 0.9);
      d[i + 2] = Math.min(255, b * shade * 0.86);
      // Tame bright moss greens so rock reads as natural cave, not garden wall.
      if (g > r * 1.05 && g > b * 1.05 && lum > 40 && lum < 140) {
        const avg = (r + g + b) / 3;
        d[i] = Math.min(255, avg * 0.92);
        d[i + 1] = Math.min(255, avg * 0.88);
        d[i + 2] = Math.min(255, avg * 0.82);
      }
    }
  }
}

function composeTile(genPath, outPath, slug) {
  return loadImage(genPath).then((img) => {
    const { sx, sy, side } = centerCropSquare(img);
    const out = createCanvas(TILE, TILE);
    const ctx = out.getContext('2d');
    ctx.imageSmoothingEnabled = true;
    ctx.imageSmoothingQuality = 'high';
    ctx.drawImage(img, sx, sy, side, side, 0, 0, TILE, TILE);

    const data = ctx.getImageData(0, 0, TILE, TILE);
    tunePixels(data.data, slug);
    ctx.putImageData(data, 0, 0);

    writeFileSync(outPath, out.toBuffer('image/png'));
    console.log('wall tile', outPath);
  });
}

mkdirSync(GEN_DIR, { recursive: true });
mkdirSync(OUT_DIR, { recursive: true });
mkdirSync(SPRITE_DIR, { recursive: true });

for (const { slug, gen, sprite } of WALLS) {
  const outPath = join(OUT_DIR, `${slug}.png`);
  await composeTile(join(GEN_DIR, gen), outPath, slug);
  writeFileSync(join(SPRITE_DIR, sprite), readFileSync(outPath));
  console.log('sprite copy', join(SPRITE_DIR, sprite));
}

const embedded = {};
for (const { slug } of WALLS) {
  const buf = readFileSync(join(OUT_DIR, `${slug}.png`));
  embedded[slug] = `data:image/png;base64,${buf.toString('base64')}`;
}

writeFileSync(
  EMBED_OUT,
  `/** Auto-generated by scripts/compose-nightmare-walls.mjs — do not edit. */\n`
  + `export const NIGHTMARE_WALL_TILES = ${JSON.stringify(embedded)};\n`,
);
console.log('embedded', EMBED_OUT);